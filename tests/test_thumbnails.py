from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from threading import Condition, Event

import pytest
from fastapi.testclient import TestClient
from PIL import Image, ImageOps

from emviary import thumbnails
from emviary.api import create_app


def test_gallery_thumbnail_is_small_persistent_and_does_not_change_master(service, monkeypatch):
    client = TestClient(create_app(service, schedule=False))
    artwork = next(a for a in service.settings.artworks if a["approved"])
    master = service.settings.art_dir / artwork["asset"]
    before = master.read_bytes()
    url = "/art-thumbnail/" + artwork["id"]
    response = client.get(url)
    assert response.status_code == 200 and response.headers["content-type"] == "image/jpeg"
    with Image.open(BytesIO(response.content)) as image:
        assert image.width <= 480 and image.height <= 360
        with Image.open(master) as source:
            assert abs(image.width / image.height - source.width / source.height) < 0.02
    assert master.read_bytes() == before
    files = list((service.settings.data_dir / "cache" / "thumbnails").glob("*.jpg"))
    assert len(files) == 1 and files[0].read_bytes() == response.content

    def should_not_decode(*args):
        pytest.fail("A persisted cache hit decoded the master again")

    monkeypatch.setattr(thumbnails, "_render_thumbnail", should_not_decode)
    # A newly created application can serve a thumbnail generated by another.
    restarted = TestClient(create_app(service, schedule=False))
    assert restarted.get(url).content == response.content
    cached = restarted.get(url, headers={"If-None-Match": response.headers["etag"]})
    assert cached.status_code == 304 and not cached.content
    assert client.get("/art-thumbnail/unknown-artwork").status_code == 404
    assert 'src="/art-thumbnail/' in client.get("/library").text
    assert client.get("/art/" + artwork["id"]).content == before


def test_thumbnail_matches_original_jpeg_recipe_and_invalidates_on_master_change(tmp_path):
    master = tmp_path / "master.png"
    with Image.new("RGBA", (901, 607), (10, 80, 160, 100)) as source:
        source.putpixel((100, 150), (255, 200, 0, 255))
        source.save(master)
    # Compatibility oracle: the previously deployed thumbnail recipe.
    with Image.open(master) as source:
        image = ImageOps.exif_transpose(source).convert("RGBA")
        image.thumbnail((480, 360), Image.Resampling.LANCZOS)
        background = Image.new("RGB", image.size, "white")
        background.paste(image, mask=image.getchannel("A"))
        with BytesIO() as output:
            background.save(output, format="JPEG", quality=82, optimize=True)
            expected = output.getvalue()
        image.close()
        background.close()
    st = master.stat()
    first, tag = thumbnails.thumbnail_file(master, st.st_mtime_ns, st.st_size, tmp_path / "cache")
    assert first.read_bytes() == expected
    with Image.new("RGB", (901, 607), "red") as source:
        source.save(master)
    st = master.stat()
    second, second_tag = thumbnails.thumbnail_file(
        master, st.st_mtime_ns, st.st_size, tmp_path / "cache"
    )
    assert second != first and second_tag != tag


def test_concurrent_cache_misses_decode_at_most_two_images(tmp_path, monkeypatch):
    condition, release = Condition(), Event()
    active = peak = entered = 0

    def blocking_render(source, target):
        nonlocal active, peak, entered
        with condition:
            active += 1
            entered += 1
            peak = max(peak, active)
            condition.notify_all()
        assert release.wait(5)
        target.write(b"cached-image")
        with condition:
            active -= 1

    monkeypatch.setattr(thumbnails, "_render_thumbnail", blocking_render)
    with ThreadPoolExecutor(max_workers=8) as pool:
        futures = [
            pool.submit(thumbnails.thumbnail_file, tmp_path / str(i), i, 1, tmp_path / "cache")
            for i in range(8)
        ]
        try:
            with condition:
                assert condition.wait_for(lambda: entered == 2, timeout=5)
                assert active == peak == 2
        finally:
            release.set()
        for future in futures:
            path, _ = future.result(timeout=5)
            assert path.read_bytes() == b"cached-image"
    assert entered == 8 and peak == 2
    assert not list((tmp_path / "cache").glob("*.tmp"))


def test_failed_generation_leaves_no_partial_cache_and_releases_slot(tmp_path, monkeypatch):
    def broken_render(source, target):
        target.write(b"partial")
        raise OSError("generation failed")

    monkeypatch.setattr(thumbnails, "_render_thumbnail", broken_render)
    for i in range(3):
        with pytest.raises(OSError):
            thumbnails.thumbnail_file(tmp_path / "master", i, 1, tmp_path / "cache")
    assert not list((tmp_path / "cache").iterdir())
